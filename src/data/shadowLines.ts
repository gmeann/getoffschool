let bag: string[] = []

/** 같은 말이 연달아 나오지 않도록 섞어서 하나씩 꺼냄 */
export function pickShadowLine(): string {
  if (bag.length === 0) {
    bag = [...SHADOW_LINES]
    for (let i = bag.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1))
      ;[bag[i], bag[j]] = [bag[j], bag[i]]
    }
  }
  return bag.pop()!
}
